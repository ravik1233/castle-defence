/**
 * Every enemy in the game, family by family. A region draws only from its
 * own, so what changes when the player crosses a border is who they are
 * fighting rather than how many.
 */
export const ENEMIES: EnemyDef[] = [
  ...GOBLINS_AND_ORCS,
  ...UNDEAD,
  ...BEASTS,
  ...DROWNED,
  ...FALLEN,
  ...DEMONS,
];

export const ENEMY_BY_ID = new Map(ENEMIES.map((e) => [e.id, e]));

/** Everyone belonging to one horde, for wave building and the ledger. */
export function familyOf(family: EnemyFamily): EnemyDef[] {
  return ENEMIES.filter((e) => e.family === family);
}

export function enemy(id: string): EnemyDef {
  const e = ENEMY_BY_ID.get(id);
  if (!e) throw new Error(`unknown enemy ${id}`);
  return e;
}
